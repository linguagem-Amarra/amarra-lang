test('edição recompila condições e repetições e rejeita erros reais', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('5 movimentos prontos para visualizar.')).toBeVisible()
  const editor = page.getByRole('textbox', { name: 'Código Amarra' })
  await editor.fill('no "editado" { cruzar a b; inteiro n = 2 + 1; repetir n { enrolar a 1; } se falso { passar_cima b; } senao { apertar; } finalizar "ok"; }')
  await expect(page.getByRole('button', { name: 'Reproduzir animação', exact: true })).toBeDisabled()
  await editor.press('Control+Enter')
  await expect(page.getByText('6 movimentos prontos para visualizar.')).toBeVisible({ timeout: 15000 })
  await expect(page.locator('.step').filter({ hasText: 'Enrolar a ponta' })).toHaveCount(3)
  await editor.fill('no "erro" { passar_baixo a; }')
  await editor.press('Control+Enter')
  await expect(page.locator('.error-item')).toContainText('Use cruzar')
  await expect(page.getByRole('button', { name: 'Reproduzir animação', exact: true })).toBeDisabled()
  await editor.fill('no "erro" { @ }')
  await editor.press('Control+Enter')
  await expect(page.locator('.error-item')).toContainText('lexico')
})

