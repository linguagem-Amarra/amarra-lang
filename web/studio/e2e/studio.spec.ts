test('duas passagens, organização e aperto são fases distintas e podem ser buscadas', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByText('5 movimentos prontos para visualizar.')).toBeVisible()
  const timeline = page.getByRole('slider', { name: 'Posição da animação' })
  for (const [position, label] of [['.5', 'Formar o laço'], ['1.5', 'Primeira passagem pela abertura'],
    ['2.5', 'Segunda passagem pela mesma abertura'], ['3.15', 'Organizar as duas passagens'],
    ['3.7', 'Apertar gradualmente'], ['5', 'Nó simples duplo finalizado']]) {
    await timeline.fill(position)
    await expect(page.locator('.motion-caption')).toContainText(label)
    await page.waitForTimeout(300)
    await page.locator('.scene').screenshot({ path: `../../.studio-cache/double-stage-${position}.png` })
  }
  await page.getByRole('button', { name: 'Visão geral', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Visão geral', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Foco no nó', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Foco no nó', exact: true })).toHaveAttribute('aria-pressed', 'true')
  const editor = page.getByRole('textbox', { name: 'Código Amarra' })
  await editor.fill((await editor.inputValue()).replace('no "no simples duplo"', 'no "renomeado"'))
  await editor.press('Control+Enter')
  await expect(page.getByText('5 movimentos prontos para visualizar.')).toBeVisible()
  await expect(page.locator('.scene-caption h2')).toHaveText('renomeado')
  await expect(page.getByText('Nó simples duplo · duas passagens · uma corda', { exact: true })).toBeVisible()
  // Um único passe continua sendo um programa válido, sem alegar ser o nó duplo.
  await editor.fill((await editor.inputValue()).replace('    passar_baixo ponta_trabalho;\n', ''))
  await editor.press('Control+Enter')
  await expect(page.getByText('4 movimentos prontos para visualizar.')).toBeVisible()
  await expect(page.getByText('Nó simples duplo · duas passagens · uma corda', { exact: true })).not.toBeVisible()
  expect(errors).toEqual([])
})

test('reprodução completa permite girar a câmera e termina com o nó imóvel', async ({ page }) => {
  test.setTimeout(45000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByText('5 movimentos prontos para visualizar.')).toBeVisible()
  const timeline = page.getByRole('slider', { name: 'Posição da animação' })
  await page.getByRole('combobox', { name: 'Velocidade da animação' }).selectOption('2')
  await page.getByRole('button', { name: 'Reproduzir animação', exact: true }).click()
  await expect.poll(async () => Number(await timeline.inputValue())).toBeGreaterThan(.1)
  const box = (await page.locator('canvas').boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 80, box.y + box.height / 2 + 35, { steps: 8 }); await page.mouse.up()
  await expect(timeline).toHaveValue('5', { timeout: 25000 })
  await expect(page.locator('.motion-caption')).toContainText('Nó simples duplo finalizado')
  await expect(page.getByRole('button', { name: 'Reproduzir animação', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Visão geral', exact: true }).click()
  await page.waitForTimeout(1200)
  await timeline.fill('4.15'); await page.waitForTimeout(300)
  const first = await page.locator('canvas').screenshot()
  await timeline.fill('4.85'); await page.waitForTimeout(300)
  const last = await page.locator('canvas').screenshot()
  expect(first.equals(last)).toBe(true)
  expect(errors).toEqual([])
})

test('velocidade, passos e continuação automática controlam a reprodução', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('5 movimentos prontos para visualizar.')).toBeVisible()
  const timeline = page.getByRole('slider', { name: 'Posição da animação' })
  await page.getByRole('button', { name: 'Próximo passo', exact: true }).click()
  await expect(timeline).toHaveValue('1')
  await page.getByRole('button', { name: 'Passo anterior', exact: true }).click()
  await expect(timeline).toHaveValue('0')
  await page.getByRole('checkbox', { name: 'Continuar entre etapas automaticamente' }).uncheck()
  await timeline.fill('.9')
  await page.getByRole('combobox', { name: 'Velocidade da animação' }).selectOption('2')
  await page.getByRole('button', { name: 'Reproduzir animação', exact: true }).click()
  await expect(timeline).toHaveValue('1', { timeout: 4000 })
  await expect(page.getByRole('button', { name: 'Reproduzir animação', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Reiniciar animação', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Continuar entre etapas automaticamente' }).check()
  await page.getByRole('combobox', { name: 'Velocidade da animação' }).selectOption('0.25')
  await page.getByRole('button', { name: 'Reproduzir animação', exact: true }).click()
  await page.waitForTimeout(800)
  await page.getByRole('button', { name: 'Pausar animação', exact: true }).click()
  const slow = Number(await timeline.inputValue())
  await page.getByRole('button', { name: 'Reiniciar animação', exact: true }).click()
  await page.getByRole('combobox', { name: 'Velocidade da animação' }).selectOption('2')
  await page.getByRole('button', { name: 'Reproduzir animação', exact: true }).click()
  await page.waitForTimeout(800)
  await page.getByRole('button', { name: 'Pausar animação', exact: true }).click()
  expect(Number(await timeline.inputValue())).toBeGreaterThan(slow * 3)
})

