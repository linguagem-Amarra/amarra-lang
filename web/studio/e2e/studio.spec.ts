test('abrir, baixar, grade, ajuda e layout móvel funcionam', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByText('5 movimentos prontos para visualizar.')).toBeVisible()
  await page.locator('input[type=file]').setInputFiles({ name: 'meu-no.amr', mimeType: 'text/plain',
    buffer: Buffer.from('no "arquivo" { cruzar a b; passar_baixo a; finalizar "feito"; }') })
  await page.getByRole('button', { name: 'Compilar código' }).click()
  await expect(page.getByText('3 movimentos prontos para visualizar.')).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Baixar código Amarra' }).click()
  expect((await download).suggestedFilename()).toBe('meu-no.amr')
  const grid = page.getByRole('button', { name: 'Mostrar grade', exact: true })
  await grid.click()
  await expect(grid).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('button', { name: 'Como usar' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: 'Fechar ajuda' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({ path: '../../.studio-cache/studio-mobile.png', fullPage: true })
})
